"""Markdown validation report, committed under docs/validation/ as evidence."""


def _pct(x: float | None) -> str:
    return "–" if x is None else f"{x * 100:+.2f}%"


def validation_markdown(measurements: dict, validation: dict) -> str:
    run, qc = measurements["run"], validation["qc"]
    lines = [
        f"# Validation report — {validation['specimen_id']}",
        "",
        (f"Pipeline {run['pipeline_version']} · run {run['started_at'][:19]} UTC · "
        f"QC **{qc['summary']['status']}** ({qc['summary']['error']} errors, "
        f"{qc['summary']['warning']} warnings, {qc['summary']['info']} info)"),
        "",
        "Generated by `cochleahub validate`. Method and thresholds: `docs/DECISIONS.md` D7, D14.",
        "",
    ]

    if slicer := validation["slicer"]:
        lines += [
            f"## Against {slicer['tool']}",
            "",
            f"Same segmentation; Slicer closed surface smoothing {slicer['closed_surface_smoothing']}.",
            "",
            "| Structure | Voxels equal | Volume diff | Surface area diff |",
            "| --- | --- | --- | --- |",
        ]
        for name, r in slicer["structures"].items():
            same = "yes" if r["voxel_count_ours"] == r["voxel_count_slicer"] else "**no**"
            lines.append(
                f"| {name} | {same} | {_pct(r['volume_rel_diff'])} | "
                f"{_pct(r['surface_area_rel_diff'])} |"
            )
        lines.append("")

    dm = validation["dataset_meshes"]
    lines += [
        "## Against the meshes published with the dataset",
        "",
        f"Reference: {dm['reference']}. Surface distances are symmetric, vertex to vertex.",
        "",
        "| Structure | Volume diff | Area diff | Mean dist (mm) | 95th pct (mm) | Max (mm) |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for name, r in dm["structures"].items():
        lines.append(
            f"| {name} | {_pct(r['volume_rel_diff'])} | {_pct(r['surface_area_rel_diff'])} | "
            f"{r['mean_mm']:.3f} | {r['p95_mm']:.3f} | {r['max_mm']:.3f} |"
        )
    lines.append("")

    if acc := validation["dataset_accuracy_report"]:
        lines += [
            "## Dataset's own accuracy (CBCT vs. histology)",
            "",
            (f"From `{acc['source']}`: Hausdorff mean {acc['hausdorff_mean']}, "
            f"max {acc['hausdorff_max']}; volume error {acc['volume_error_percent']}%. "
            "This bounds how well the segmentation itself matches the specimen."),
            "",
        ]

    lines += ["## QC flags", "", "| Severity | Code | Structure | Detail | Source |",
              "| --- | --- | --- | --- | --- |"]
    order = {"error": 0, "warning": 1, "info": 2}
    for f in sorted(qc["flags"], key=lambda f: order[f["severity"]]):
        lines.append(
            f"| {f['severity']} | {f['code']} | {f['structure'] or '–'} | {f['message']} | "
            f"{f['source'] or '–'} |"
        )
    return "\n".join(lines) + "\n"
