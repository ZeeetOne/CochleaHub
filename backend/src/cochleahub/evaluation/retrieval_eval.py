"""Retrieval evaluation (stage 8, D19): is the right passage among the top k?

30 author-written queries, each labelled with the passages that answer it (id prefixes, so a
label survives a status change in a decision title). Half are lexical ("code": QC flag codes,
reference keys, tool names), the rest paraphrases; all in English. The same queries run through BM25
only, dense only, and the hybrid with RRF, as in BEIR's comparison of lexical and dense
retrievers [Thakur2021].

Metrics: hit@1 and hit@5 (a relevant passage among the first k) and MRR@10.
"""

import json
from pathlib import Path

from cochleahub.config import REPO_ROOT
from cochleahub.evaluation.assistant_eval import wilson

QUERIES = REPO_ROOT / "evaluation" / "retrieval" / "queries.json"
MODES = ("bm25", "dense", "hybrid")


def is_relevant(chunk_id: str, relevant: list[str]) -> bool:
    return any(chunk_id.startswith(r) for r in relevant)


def evaluate(index) -> dict:
    queries = json.loads(QUERIES.read_text(encoding="utf-8"))
    out: dict = {"queries": len(queries), "corpus_passages": len(index.chunks),
                 "embedding_model": index.embedder.name if index.embedder else None, "modes": {},
                 "per_query": []}
    per_query = {q["id"]: {"id": q["id"], "kind": q["kind"], "query": q["query"]} for q in queries}
    for mode in MODES:
        rows = []
        for q in queries:
            hits = index.search(q["query"], k=10, mode=mode)
            ranks = [i + 1 for i, h in enumerate(hits) if is_relevant(h.chunk.id, q["relevant"])]
            first = ranks[0] if ranks else None
            rows.append({"kind": q["kind"], "first": first})
            per_query[q["id"]][mode] = {"first_relevant_rank": first,
                                        "top1": hits[0].chunk.id if hits else None}

        def summary(subset):
            n = len(subset)
            h1 = sum(1 for r in subset if r["first"] == 1)
            h5 = sum(1 for r in subset if r["first"] and r["first"] <= 5)
            mrr = sum(1 / r["first"] for r in subset if r["first"]) / n if n else 0.0
            return {"n": n, "hit@1": h1 / n, "hit@5": h5 / n, "hit@5_ci95": wilson(h5, n),
                    "mrr@10": round(mrr, 3)}

        out["modes"][mode] = {
            "all": summary(rows),
            **{kind: summary([r for r in rows if r["kind"] == kind])
               for kind in ("code", "paraphrase")},
        }
    out["per_query"] = list(per_query.values())
    return out


def markdown(result: dict) -> str:
    lines = [
        "# Retrieval evaluation",
        "",
        (f"{result['queries']} labelled queries over {result['corpus_passages']} passages "
        "(D19). Generated by `cochleahub eval-retrieval`."),
        "",
        ("| Retriever | hit@1 | hit@5 (95% CI) | MRR@10 | hit@5 lexical | "
         "hit@5 paraphrase |"),
        "|---|---|---|---|---|---|",
    ]
    for mode, m in result["modes"].items():
        a = m["all"]
        lo, hi = a["hit@5_ci95"]
        lines.append(
            f"| {mode} | {a['hit@1']:.0%} | {a['hit@5']:.0%} ({lo:.0%}–{hi:.0%}) | "
            f"{a['mrr@10']:.2f} | {m['code']['hit@5']:.0%} (n={m['code']['n']}) | "
            f"{m['paraphrase']['hit@5']:.0%} (n={m['paraphrase']['n']}) |"
        )
    misses = [q for q in result["per_query"]
              if not (q["hybrid"]["first_relevant_rank"] or 99) <= 5]
    lines += ["", "## Hybrid misses (no relevant passage in the top 5)", ""]
    lines += [f"- {q['id']} ({q['kind']}): “{q['query']}” → top 1 was `{q['hybrid']['top1']}`"
              for q in misses] or ["None."]
    return "\n".join(lines) + "\n"


def write(result: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "results.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
    (out_dir / "README.md").write_text(markdown(result), encoding="utf-8")
